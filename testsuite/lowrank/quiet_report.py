#!/usr/bin/env python3
"""Tables for the cross-slice measurement (Task 8 step 4) and the automatic-N_delay timing (P6-3), generated from bench.sh lines.

Usage:
  python3 -I testsuite/lowrank/quiet_report.py xs docs/benchmarks/raw_cross_slice.txt  > docs/benchmarks/cross_slice.md
  python3 -I testsuite/lowrank/quiet_report.py nd docs/benchmarks/raw_auto_ndelay.txt  > docs/benchmarks/auto_ndelay.md
Decision rule (plan Tasks 6/8, spec auto-N_delay Sec. 4): a difference counts if it is > 5 % of the reference AND larger than
twice the larger relative spread ((max - min)/mean) of the two; "auto within noise of the best fixed" if auto's mean exceeds the
best fixed mean by at most max(5 %, 2 x the larger spread).
"""
import collections
import sys


def rows(path):
    out = []
    for line in open(path):
        t = line.split()
        if not t:
            continue
        r = dict(scheme=t[0], L=int(t[1]), nd=int(t[3]), sps=float(t[5]), commit=t[8])
        r["model"] = t[13] if len(t) >= 15 else "Hubbard"
        r["keys"] = t[14] if len(t) >= 15 else ""
        r["nd_used"] = next((x.split("=")[1] for x in t if x.startswith("nd_used=")), "")
        out.append(r)
    return out


mean = lambda x: sum(x) / len(x)
spread = lambda x: (max(x) - min(x)) / mean(x)


def xs(path):
    d = collections.defaultdict(list)
    for r in rows(path):
        on = "Lowrank_cross_slice=.T." in r["keys"]
        d[(r["model"], r["L"], r["scheme"], on)].append(r["sps"])
    commits = sorted({r["commit"] for r in rows(path)})
    print("# Cross-slice delay: key on vs off (Mac M1 Pro, 1 thread)\n")
    print("Generated by `testsuite/lowrank/quiet_report.py xs` from `%s` (commit(s) %s). Mz Hubbard, Beta = 2, Checkerboard,"
          " U = 8, one measured slice (LOBS_ST = LOBS_EN = 1), N_delay = 32. s/sweep, mean of the repetitions.\n"
          % (path.split("/")[-1], ", ".join(commits)))
    print("| model | L | scheme | reps | off (spread) | on (spread) | on/off | verdict |")
    print("|---|---:|---|---:|---:|---:|---:|---|")
    for (m, L, s) in sorted({k[:3] for k in d}):
        a, b = d[(m, L, s, False)], d[(m, L, s, True)]
        if not a or not b:
            continue
        ratio = mean(b) / mean(a)
        noise = 2 * max(spread(a), spread(b))
        v = "gain" if 1 - ratio > 0.05 and 1 - ratio > noise else ("loss" if ratio - 1 > 0.05 and ratio - 1 > noise else "no significant difference")
        print("| %s | %d | %s | %d | %.4f (%.1f %%) | %.4f (%.1f %%) | %.3f | %s |" % (
            m, L, s, len(a), mean(a), 100 * spread(a), mean(b), 100 * spread(b), ratio, v))


def nd(path):
    d = collections.defaultdict(list)
    used = collections.defaultdict(list)
    for r in rows(path):
        d[(r["model"], r["L"], r["scheme"], r["nd"])].append(r["sps"])
        if r["nd"] <= 0:
            used[(r["model"], r["L"], r["scheme"], r["nd"])].append(r["nd_used"])
    commits = sorted({r["commit"] for r in rows(path)})
    print("# Automatic N_delay vs fixed values (Mac M1 Pro, 1 thread)\n")
    print("Generated by `testsuite/lowrank/quiet_report.py nd` from `%s` (commit(s) %s). s/sweep, mean of the repetitions."
          " auto = N_delay 0 (static rule), tune = N_delay -1 (warm-up timing); used = N_delay chosen per repetition.\n"
          % (path.split("/")[-1], ", ".join(commits)))
    print("| model | L | scheme | best fixed (s/sweep, spread) | auto: used, s/sweep, vs best | tune: used, s/sweep, vs best | verdict auto / tune |")
    print("|---|---:|---|---|---|---|---|")
    for (m, L, s) in sorted({k[:3] for k in d}):
        fixed = {k[3]: v for k, v in d.items() if k[:3] == (m, L, s) and k[3] > 0}
        if not fixed:
            continue
        nb = min(fixed, key=lambda n: mean(fixed[n]))
        best = fixed[nb]
        cells, verdicts = [], []
        for n in (0, -1):
            x = d.get((m, L, s, n))
            if not x:
                cells.append("—"); verdicts.append("—"); continue
            rel = mean(x) / mean(best) - 1
            tol = max(0.05, 2 * max(spread(x), spread(best)))
            cells.append("%s, %.4f, %+.1f %%" % ("/".join(used[(m, L, s, n)]), mean(x), 100 * rel))
            verdicts.append("ok" if rel <= tol else "slower")
        print("| %s | %d | %s | %d: %.4f (%.1f %%) | %s | %s | %s |" % (m, L, s, nb, mean(best), 100 * spread(best),
                                                                     cells[0], cells[1], " / ".join(verdicts)))
    print("\nAll fixed values (s/sweep, mean):\n")
    print("| model | L | scheme | " + " | ".join(str(n) for n in (8, 16, 32, 64, 128)) + " |")
    print("|---|---:|---|" + "---:|" * 5)
    for (m, L, s) in sorted({k[:3] for k in d}):
        print("| %s | %d | %s | " % (m, L, s) + " | ".join(
            ("%.4f" % mean(d[(m, L, s, n)])) if d.get((m, L, s, n)) else "—" for n in (8, 16, 32, 64, 128)) + " |")


if __name__ == "__main__":
    {"xs": xs, "nd": nd}[sys.argv[1]](sys.argv[2])
