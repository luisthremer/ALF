#!/usr/bin/env python3
"""D13 table (spec D13): delayed vs submatrix for bond models, generated from bench.sh lines with model/keys fields.

Usage: python3 -I testsuite/lowrank/d13_report.py docs/benchmarks/raw_d13_bond_models.txt > docs/benchmarks/d13_bond_models.md
Rule (plan Task 6): submatrix counts as slower than delayed for a (model, L) if its mean s/sweep exceeds delayed's by > 5 %
AND by more than twice the larger relative spread ((max - min)/mean) of the two; faster correspondingly.
"""
import collections
import sys


def main(path):
    d = collections.defaultdict(list)
    commits = set()
    for line in open(path):
        t = line.split()
        if not t:
            continue
        if len(t) != 15:
            sys.exit("d13_report.py: expected 15 fields (bench.sh with KEY=VALUE): " + line.strip())
        d[(t[13], int(t[1]), t[0])].append(float(t[5]))
        commits.add(t[8])
    mean = lambda x: sum(x) / len(x)
    spread = lambda x: (max(x) - min(x)) / mean(x)
    out = ["# D13: delayed vs submatrix for bond models (Mac M1 Pro, 1 thread, N_delay = 32)", "",
           "Generated by `testsuite/lowrank/d13_report.py` from `%s` (commit(s) %s). Times in s/sweep, mean of the"
           " repetitions; spread = (max - min)/mean." % (path.split("/")[-1], ", ".join(sorted(commits))), "",
           "| model | L | reps | standard | delayed (spread) | submatrix (spread) | sub/del | speedup delayed | speedup submatrix | D13 verdict |",
           "|---|---:|---:|---:|---:|---:|---:|---:|---:|---|"]
    for m in sorted({k[0] for k in d}):
        for L in sorted({k[1] for k in d if k[0] == m}):
            st, de, su = d[(m, L, "standard")], d[(m, L, "delayed")], d[(m, L, "submatrix")]
            ratio = mean(su) / mean(de)
            noise = 2 * max(spread(de), spread(su))
            if ratio - 1 > 0.05 and ratio - 1 > noise:
                v = "submatrix slower"
            elif 1 - ratio > 0.05 and 1 - ratio > noise:
                v = "submatrix faster"
            else:
                v = "equal within noise"
            out.append("| %s | %d | %d | %.4f | %.4f (%.1f %%) | %.4f (%.1f %%) | %.3f | %.2f | %.2f | %s |" % (
                m, L, len(de), mean(st), mean(de), 100 * spread(de), mean(su), 100 * spread(su), ratio,
                mean(st) / mean(de), mean(st) / mean(su), v))
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
