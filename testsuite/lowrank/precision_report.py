#!/usr/bin/env python3
"""Paired precision table (scheme / standard, same seed => same trajectory) from bench.sh lines prefixed by a group tag.

Usage: python3 -I testsuite/lowrank/precision_report.py docs/benchmarks/raw_largeN_precision.txt > docs/benchmarks/largeN_precision.md
Input line: <tag> scheme L N N_delay threads sec_per_sweep acceptance nsweep commit date pgreen_mean pgreen_max pphase_max
            [model keys] [nd_used=<n>]   (bench.sh output with the group tag, e.g. _U4, in front)
       python3 -I testsuite/lowrank/precision_report.py --campaign CAMPAIGN_DIR > table.md
            (a collected campaign of testsuite/lowrank/campaign: rows from collected.tsv, precision lines from each run's latest
             attempt info; group = point name; all schemes of a point must share the seed)
Pass rule (CLAUDE.md, stability tier): every paired ratio <= 2; equal acceptance confirms the same trajectory.
"""
import csv
import os
import sys


def campaign_rows(cdir):
    rows = []
    with open(os.path.join(cdir, "collected.tsv")) as fh:
        for r in csv.DictReader(fh, delimiter="\t"):
            run = os.path.join(cdir, "runs", r["run_id"])
            info = os.path.join(run, open(os.path.join(run, "latest")).read().strip(), "info")
            g = p = acc = None
            for line in open(info):
                if "Precision Green  Mean, Max" in line:
                    g = line.split(":")[1].split()
                elif "Precision Phase, Max" in line:
                    p = float(line.split(":")[1].split()[0])
                elif line.strip().startswith("Acceptance ") and acc is None:
                    acc = line.split(":")[1].strip()
            L = int(r["L"])
            rows.append(dict(tag=r["point"], scheme=r["scheme"], L=L, N=L * L,
                             nd=int(r["n_delay_requested"]) if r["n_delay_requested"] not in ("", "n/a") else 32,
                             acc=acc, commit=r["commit"], gmean=float(g[0]), gmax=float(g[1]), pmax=p,
                             nd_used=r["n_delay_used"] if r["n_delay_mode"] == "auto" else None))
    return rows


def main(path, campaign=False):
    rows = campaign_rows(path) if campaign else []
    for line in ([] if campaign else open(path)):
        f = line.split()
        if len(f) < 14:
            continue
        nd_used = f[-1].split("=")[1] if f[-1].startswith("nd_used=") else None
        rows.append(dict(tag=f[0], scheme=f[1], L=int(f[2]), N=int(f[3]), nd=int(f[4]), acc=f[7], commit=f[9],
                         gmean=float(f[11]), gmax=float(f[12]), pmax=float(f[13]), nd_used=nd_used))
    std = {(r["tag"], r["L"]): r for r in rows if r["scheme"] == "standard"}
    commits = sorted({r["commit"] for r in rows})
    if campaign:
        print("# Paired precision, campaign %s (same seed for all schemes of a point)\n" % os.path.basename(os.path.normpath(path)))
    else:
        print("# Large-N precision pre-check (Mac M1 Pro, Mz Hubbard, Beta = 2, Nwrap = 10, 2 bins x 2 sweeps, same seed)\n")
    print("Generated by `testsuite/lowrank/precision_report.py` from `%s` (commit tag(s) %s). Ratios scheme / standard of the"
          " info lines \"Precision Green Mean, Max\" and \"Precision Phase, Max\"; rule: every ratio <= 2.\n"
          % (path.split("/")[-1], ", ".join(commits)))
    print("| %s | L | N (sites) |" % ("point" if campaign else "U") + " scheme | N_delay (used) | same acc. | Green mean | Green max | Phase max | standard Green mean / max | verdict |")
    print("|---|---:|---:|---|---|---|---:|---:|---:|---|---|")
    worst = 0.0
    for r in sorted(rows, key=lambda r: (r["tag"], r["L"], r["scheme"], r["nd"])):
        if r["scheme"] == "standard":
            continue
        s = std[(r["tag"], r["L"])]
        rg, rm = r["gmean"] / s["gmean"], r["gmax"] / s["gmax"]
        if s["pmax"] > 0:
            rp = r["pmax"] / s["pmax"]; ptxt = "%.3f" % rp
        else:   # standard phase error exactly 0 (real weights): ratio undefined, judge the absolute value (<= 1e-12 passes)
            rp = 1.0 if r["pmax"] <= 1e-12 else float("inf"); ptxt = "abs %.1e" % r["pmax"]
        worst = max(worst, rg, rm, rp)
        nd = "auto (%s)" % r["nd_used"] if r["nd"] == 0 else str(r["nd"])
        ok = "ok" if max(rg, rm, rp) <= 2 and r["acc"] == s["acc"] else "FAIL"
        print("| %s | %d | %d | %s | %s | %s | %.3f | %.3f | %s | %.2e / %.2e | %s |"
              % (r["tag"] if campaign else r["tag"].lstrip("_U"), r["L"], r["N"], r["scheme"], nd, "yes" if r["acc"] == s["acc"] else "NO",
                 rg, rm, ptxt, s["gmean"], s["gmax"], ok))
    print("\nWorst ratio: %.3f" % worst)


if __name__ == "__main__":
    if sys.argv[1] == "--campaign":
        main(sys.argv[2], campaign=True)
    else:
        main(sys.argv[1])
