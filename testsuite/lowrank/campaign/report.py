#!/usr/bin/env python3
"""Markdown report of one or more collected campaigns (runs locally, stdlib only).

Usage: python3 -I report.py COLLECTED.json [COLLECTED.json ...] [--out FILE.md]

Numbers come only from collect.py output (which reads the logs written by the job scripts). Refuses (exit 2) to mix
commits, binaries (sha256) or machines (cluster + CPU model) across the valid rows of all inputs.
Tables:
  Groups never pool configurations: the key includes campaign, fakeintel, MKL ISA and MKL threading layer ("config").
  1. per point x L x layout x scheme x N_delay x config: n_valid (flagged "<3!" below three repetitions), median
     s/sweep, range [min, max] over the repetitions, spread,
     speedup vs the standard scheme (same point, L, layout, config), N_delay used, median setup time and max RSS (an
     upper bound, marked "<=", where only the job-level sacct value exists);
  2. layouts: node throughput = ranks / (s per sweep) (sweeps per second per node, all ranks counted) per layout;
  3. timing split (runs with a T1 timers.txt): s/sweep of the nine exclusive categories over bins >= 2 (bin 1 dropped),
     mean over ranks, median over repetitions, share of `sweep` (their sum); `sweep` of the slowest rank and
     `bin_overhead` shown separately (not categories); counters per sweep; flush_unattributed != 0 flagged.
Excluded (FAILED / INVALID) and missing runs are listed with their status.
"""
import hashlib
import json
import os
import statistics
import sys
from collections import OrderedDict, defaultdict


def sha256(path):
    return hashlib.sha256(open(path, "rb").read()).hexdigest()


def fmt(x, nd=4):
    if x is None:
        return "-"
    if isinstance(x, float):
        return "%.*g" % (nd, x)
    return str(x)


def table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(fmt(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def single(rows, key, what):
    vals = sorted(set(str(r[key]) for r in rows))
    if len(vals) > 1:
        sys.stderr.write("report.py: refusing to mix %s: %s\n" % (what, ", ".join(vals)))
        sys.exit(2)
    return vals[0] if vals else "-"


CATEGORIES = ("update", "flush", "vwrap", "hop", "stab", "meas", "global", "langevin_hmc", "other")


def split_per_sweep(t):
    """T1 timers.txt (collect.parse_timers) -> (per-sweep values, counters per sweep).
    Bins >= 2 only (bin 1 holds setup / Lowrank_init). Values: seconds per sweep from the 'mean' column (mean over
    ranks: the nine exclusive categories add up to 'sweep' exactly, so shares are consistent) plus 'sweep_max' (slowest
    rank's sweep) and 'bin_overhead' (outside the sweeps, not a category). Counters: per sweep (mean over ranks), except
    flush_rank_mean, which is averaged over the bins."""
    bins = sorted((b for b in t["sweeps"] if int(b) >= 2), key=int)
    sweeps = sum(t["sweeps"][b] for b in bins)
    if not sweeps:
        return {}, {}
    val, cnt = defaultdict(float), defaultdict(float)
    for b in bins:
        e = t["timers"][b]
        for k in CATEGORIES + ("sweep", "bin_overhead"):
            val[k] += e[k]["mean"]
        val["sweep_max"] += e["sweep"]["max"]
        for k, c in t["counters"].get(b, {}).items():
            cnt[k] += c["mean"]
    out = {k: v / sweeps for k, v in val.items()}
    cnts = {k: (v / len(bins) if k == "flush_rank_mean" else v / sweeps) for k, v in cnt.items()}
    return out, cnts


def main(argv):
    out_path = None
    if "--out" in argv:
        out_path = argv[argv.index("--out") + 1]
        argv = [a for a in argv if a not in ("--out", out_path)]
    inputs = argv[1:]
    if not inputs:
        sys.exit(__doc__)
    data = [json.load(open(p)) for p in inputs]
    rows = [r for d in data for r in d["rows"]]
    ids = [(r["campaign_id"], r["run_id"]) for r in rows]
    if len(set(ids)) != len(ids):
        sys.stderr.write("report.py: duplicate runs across inputs\n")
        return 2
    if not rows:
        sys.stderr.write("report.py: no valid rows\n")
        return 2
    commit = single(rows, "commit", "commits")
    binsha = single(rows, "job.binary_sha256", "binaries")
    for r in rows:
        r["machine"] = "%s / %s" % (r["job.cluster"], r["job.cpu_model"])
    machine = single(rows, "machine", "machines")
    L = []
    L.append("# Benchmark campaign report: %s" % ", ".join(sorted(set(d["campaign_id"] for d in data))))
    L.append("")
    L.append("Generated by `testsuite/lowrank/campaign/report.py` from collect.py output; every number below comes from "
             "the logs written by the generated job scripts.")
    L.append("")
    L.append("- Inputs: " + "; ".join("`%s` (sha256 %s)" % (os.path.relpath(p), sha256(p)[:12]) for p in inputs))
    L.append("- Commit: %s; binary sha256: %s" % (commit, binsha))
    L.append("- Machine: %s; nodes: %s" % (machine, ", ".join(sorted(set(r["job.node"] for r in rows)))))
    for key, label in (("job.build_compiler_version", "Compiler"), ("job.build_flags_prog", "Flags"),
                       ("job.mkl_version", "MKL"), ("job.mkl_isa", "MKL ISA"), ("job.mkl_threading", "MKL threading"),
                       ("job.fakeintel", "fakeintel"), ("job.mpi_version", "MPI"), ("job.ear", "EAR"),
                       ("job.governor_job_start", "Governor")):
        L.append("- %s: %s" % (label, "; ".join(sorted(set(str(r.get(key)) for r in rows)))))
    L.append("- Runs: %d valid, %d excluded, %d missing" % (len(rows), sum(len(d["excluded"]) for d in data),
                                                             sum(len(d["missing"]) for d in data)))
    L.append("")

    # A group never pools configurations: campaign, fakeintel, MKL ISA and MKL threading layer are part of the key
    # (column "config"); speedups compare with the standard scheme of the same config.
    def config(r):
        return "%s fi=%s %s %s" % (r["campaign_id"], r["job.fakeintel"], r["job.mkl_isa"], r["job.mkl_threading"])

    groups = OrderedDict()
    for r in sorted(rows, key=lambda r: (r["point"], r["L"], r["ranks"], r["threads"], config(r), r["scheme"] != "standard",
                                         r["scheme"], str(r["n_delay_requested"]), r["repetition"])):
        groups.setdefault((r["point"], r["L"], r["layout"], r["scheme"], str(r["n_delay_requested"]), config(r)),
                          []).append(r)
    med = {k: statistics.median(x["sec_per_sweep"] for x in g) for k, g in groups.items()}
    few = [k for k, g in groups.items() if len(g) < 3]
    T = []
    for k, g in groups.items():
        sps = [x["sec_per_sweep"] for x in g]
        std = med.get((k[0], k[1], k[2], "standard", "n/a", k[5]))
        m = med[k]
        rss = statistics.median(float(x["run.max_rss_kb"]) for x in g) / 1024.0
        upper = any(x.get("rss_upper_bound") for x in g)
        T.append([k[0], k[1], k[2], k[3], k[4], k[5], ",".join(sorted(set(str(x["n_delay_used"]) for x in g))),
                  "%d%s" % (len(g), " (<3!)" if len(g) < 3 else ""), m, "[%s, %s]" % (fmt(min(sps)), fmt(max(sps))),
                  "%.1f %%" % (100.0 * (max(sps) - min(sps)) / m) if m else "-",
                  (std / m) if std else None, statistics.median(x["acceptance"] for x in g),
                  statistics.median(x["setup_s"] for x in g),
                  ("<= %s (sacct, job level)" % fmt(rss)) if upper else rss])
    L.append("## 1. Time per sweep (median and range over repetitions)")
    L.append("")
    if few:
        L.append("**%d of %d groups have fewer than 3 valid repetitions (marked `<3!`): median and range are not "
                 "reliable there.**" % (len(few), len(groups)))
        L.append("")
    L.append(table(["point", "L", "layout", "scheme", "N_delay req", "config", "N_delay used", "n_valid",
                    "median s/sweep", "range", "spread", "speedup vs std", "acceptance", "setup s", "max RSS MiB"], T))
    L.append("")
    L.append("config = campaign, fakeintel, MKL ISA, MKL threading layer. max RSS: `/usr/bin/time` per rank (max over "
             "ranks); values marked `<=` come from the sacct fallback (job-level MaxRSS of all steps so far: an upper "
             "bound for the run).")
    L.append("")

    L.append("## 2. Layouts: node throughput (ranks / s per sweep)")
    L.append("")
    T = []
    for k, g in groups.items():
        T.append([k[0], k[1], k[3], k[4], k[5], k[2], g[0]["ranks"], g[0]["threads"], len(g), med[k],
                  g[0]["ranks"] / med[k]])
    T.sort(key=lambda t: (t[0], t[1], t[2], t[3], t[4], t[6]))
    L.append(table(["point", "L", "scheme", "N_delay req", "config", "layout", "ranks", "threads", "n_valid",
                    "median s/sweep", "node sweeps/s"], T))
    L.append("")

    L.append("## 3. Timing split (T1 timers.txt; bins >= 2; median over repetitions)")
    L.append("")
    T, C, flagged = [], [], []
    for k, g in groups.items():
        runs_t = [x for x in g if x.get("timers")]
        splits = [split_per_sweep(x["timers"]) for x in runs_t]
        splits = [s for s in splits if s[0]]
        if not splits:
            continue
        flagged += ["%s (flush_unattributed max %g)" % (x["run_id"], x["timers"]["flush_unattributed_max"])
                    for x in runs_t if x["timers"].get("flush_unattributed_max")]
        tot = statistics.median(s[0]["sweep"] for s in splits)
        for c in CATEGORIES:
            v = statistics.median(s[0][c] for s in splits)
            T.append(list(k) + [len(splits), c, v, "%.1f %%" % (100 * v / tot) if tot else "-"])
        T.append(list(k) + [len(splits), "**sweep** (sum of the nine)", tot, "100 %"])
        T.append(list(k) + [len(splits), "sweep, slowest rank", statistics.median(s[0]["sweep_max"] for s in splits), "-"])
        T.append(list(k) + [len(splits), "bin_overhead (outside the sweeps)",
                            statistics.median(s[0]["bin_overhead"] for s in splits), "-"])
        for c in sorted(set(c for s in splits for c in s[1])):
            C.append(list(k) + [len(splits), c, statistics.median(s[1].get(c, 0.0) for s in splits),
                                "mean over bins" if c == "flush_rank_mean" else "per sweep"])
    if T:
        L.append("Seconds per sweep, mean over ranks (the nine exclusive categories add up to `sweep`); share = of `sweep`.")
        L.append("")
        L.append(table(["point", "L", "layout", "scheme", "N_delay req", "config", "n", "category", "s/sweep", "share"], T))
        L.append("")
        L.append(table(["point", "L", "layout", "scheme", "N_delay req", "config", "n", "counter", "value", "unit"], C))
        L.append("")
        L.append("**flush_unattributed != 0 (timer attribution bug, must be 0): %s**" % ", ".join(flagged) if flagged
                 else "flush_unattributed = 0 in every run.")
    else:
        L.append("No run has a timers.txt (binary built without -DALF_TIMERS): timing split absent.")
    L.append("")

    L.append("## 4. Excluded and missing runs")
    L.append("")
    T = [[d["campaign_id"], e["run_id"], e["status"], e["attempts"], e.get("log", "-")] for d in data for e in d["excluded"]]
    T += [[d["campaign_id"], m["run_id"], "missing: " + m["status"], m["attempts"], "-"] for d in data for m in d["missing"]]
    L.append(table(["campaign", "run", "status", "attempts", "log"], T) if T else "None.")
    L.append("")
    text = "\n".join(L)
    if out_path:
        open(out_path, "w").write(text)
        print("report.py: wrote %s" % out_path)
    else:
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
